package com.sakurasoul.apartment.tenant;

/**
 * ผลการค้นชื่อผู้เช่าหนึ่งคน (SSK-174) ชื่อค่าตรงกับ TenantMatch ใน frontend/src/api/types.ts
 * <p>
 * ลำดับที่ประกาศคือลำดับความตรงจากมากไปน้อย ใช้ ordinal เรียงผลได้ตรง ๆ เหมือน MATCH_RANK ฝั่งหน้าเว็บ
 * ห้ามสลับลำดับ ไม่งั้นผลแบบคล้ายจะขึ้นก่อนผลที่ตรงทั้งคำ
 */
public enum TenantMatch {
    /** ตรงทั้งชื่อหรือตรงทั้งคำ เช่น kant กับ Kant Srisuk */
    EXACT,
    /** ชื่อหรือคำใดคำหนึ่งขึ้นต้นด้วยคำค้น */
    PREFIX,
    /** คำค้นอยู่กลางชื่อ ชื่อไทยที่ไม่เว้นวรรคระหว่างพยางค์เจอด้วยแบบนี้ */
    CONTAINS,
    /** พิมพ์ผิดไม่เกินเกณฑ์ เช่น krant กับ Kant */
    SIMILAR
}
