-- ชนิดห้อง (SSK-127 / feedback อาจารย์ 13 ก.ย. ข้อ 5)
--
-- อาจารย์สั่งว่าค่าเช่าต้องฟิกตามชนิดห้อง ไม่ใช่ให้แอดมินกรอกเอง แต่ตาราง room
-- ไม่เคยมีคอลัมน์ชนิดห้องเลย หน้าเว็บจึงเดาเอาจากเลขห้องคู่คี่ (TenantsPage.buildRows)
-- และ client.ts เติม roomType เป็น 'SINGLE' ให้ทุกห้องที่ backend ไม่ได้ส่งมา
-- แปลว่าพอหน้าเว็บต่อ backend จริง ทุกห้องจะกลายเป็น Single หมด
--
-- migration นี้เพิ่มแค่ "คอลัมน์ชนิดห้อง" อย่างเดียว ยังไม่ยุ่งกับค่าเช่า
-- เพราะคอลัมน์นี้ถูกต้องไม่ว่าคำตอบเรื่องค่าเช่าจะออกมาทางไหน ส่วนการย้ายค่าเช่า
-- ไปผูกกับชนิดห้อง (และเลิกใช้ room.base_rent) อยู่ใน V12 ซึ่งรอคำตอบอยู่
--
-- VARCHAR + CHECK ไม่ใช่ enum ของ postgres ตาม convention เดียวกับ billing_cycle
-- และ status ใน V4 ฝั่ง Java map ด้วย @Enumerated(EnumType.STRING) เหมือนกัน
-- เหตุผลคือการเพิ่มค่าใหม่ใน enum ของ postgres ต้อง ALTER TYPE ซึ่งรันใน transaction
-- เดียวกับ migration อื่นไม่ได้ในบางเวอร์ชัน ส่วน CHECK แก้ได้ด้วย DDL ธรรมดา
ALTER TABLE room ADD COLUMN room_type VARCHAR(10);

