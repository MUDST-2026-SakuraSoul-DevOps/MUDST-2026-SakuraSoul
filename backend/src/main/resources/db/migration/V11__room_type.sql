-- ถ้าอาจารย์ตอบมาเป็นอย่างอื่น แก้ที่ CASE บรรทัดล่างนี้บรรทัดเดียว
UPDATE room
SET room_type = CASE WHEN floor = 1 THEN 'SINGLE' ELSE 'DOUBLE' END;

ALTER TABLE room ALTER COLUMN room_type SET NOT NULL;

ALTER TABLE room ADD CONSTRAINT room_type_ck CHECK (room_type IN ('SINGLE', 'DOUBLE'));
