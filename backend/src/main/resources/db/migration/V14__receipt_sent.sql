-- ใบเสร็จจำว่าเคยส่งอีเมลให้ผู้เช่าไปแล้วเมื่อไหร่และกี่ครั้ง (SSK-143 ส่วน backend ของ SSK-130)
--
-- ป็อปอัป Send Invoices ต้องบอกแอดมินก่อนกดว่าใบไหนเคยส่งไปแล้ว ไม่งั้นผู้เช่าจะได้อีเมลฉบับเดิมซ้ำ
-- โดยที่แอดมินไม่รู้ตัว การส่งซ้ำยังทำได้ (เช่นผู้เช่าบอกว่าไม่ได้รับ) แต่ต้องเป็นการตัดสินใจที่เห็นตัวเลขอยู่ตรงหน้า
--
-- ทำไมเป็นสองคอลัมน์ ไม่ใช่ตารางประวัติการส่ง
-- สิ่งที่หน้าเว็บต้องใช้มีแค่ "ส่งล่าสุดเมื่อไหร่" กับ "ส่งไปกี่ครั้ง" ตารางประวัติที่เก็บทุกครั้งพร้อมอีเมลปลายทาง
-- ต้องมี endpoint และหน้าจอของมันเองถึงจะมีคนได้ใช้ ถ้าวันหนึ่งต้องตอบว่าแต่ละครั้งส่งไปที่อีเมลไหน ค่อยเพิ่มตารางนั้น
--
-- ใบที่มีอยู่แล้วได้ 0 ครั้งและไม่มีเวลาที่ส่ง ตรงกับความจริง เพราะก่อนหน้านี้ระบบส่งอีเมลไม่ได้เลย
ALTER TABLE receipt ADD COLUMN last_sent_at TIMESTAMPTZ;
ALTER TABLE receipt ADD COLUMN sent_count INTEGER NOT NULL DEFAULT 0;

-- ผูกสองคอลัมน์ไว้ด้วยกันแบบเดียวกับ receipt_paid_ck ใน V9 จะมีใบที่นับว่าส่งแล้วแต่ไม่มีเวลาที่ส่ง
-- หรือมีเวลาที่ส่งแต่นับเป็นศูนย์ไม่ได้ เพราะหน้าเว็บโชว์สองค่านี้คู่กันเสมอ (Emailed ×2 · 25 Sep 2026)
ALTER TABLE receipt ADD CONSTRAINT receipt_sent_ck
    CHECK (sent_count >= 0 AND ((sent_count > 0) = (last_sent_at IS NOT NULL)));
