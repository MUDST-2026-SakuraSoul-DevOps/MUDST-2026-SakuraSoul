-- ติดตามสต็อกและแจ้งเตือนของใกล้หมด (SSK-171)
--
-- เกณฑ์ใกล้หมดเปลี่ยนจาก stock < min_stock เป็น stock <= min_stock ตาม AC ของการ์ด (เหลือเท่าขั้นต่ำพอดีต้องเตือนแล้ว)
-- เกณฑ์อยู่ที่ SupplyItem.isLowStock ไม่ได้เก็บในตาราง migration นี้จึงไม่ต้องแก้แถวไหน
-- คอมเมนต์ของ min_stock ใน V8 ยังเขียนว่า < แก้ไม่ได้ เพราะ Flyway เทียบ checksum ของไฟล์ที่รันไปแล้ว

-- การตั้งยอดคงเหลือใหม่ตรง ๆ จากฟอร์มแก้ไข (PUT /api/supplies/{id}) หนึ่งแถวต่อการแก้ที่ทำให้ยอดเปลี่ยน
-- quantity คือส่วนต่าง (ยอดใหม่ลบยอดเดิม) ไม่ใช่ยอดใหม่ ประวัติความเคลื่อนไหว (GET /api/supplies/{id}/movements)
-- จึงบวกแถวนี้ต่อกับการเติม (supply_restock) และการเบิก (maintenance_supply_usage) ได้ตรง ๆ
--
-- ไม่ cascade เหมือน supply_restock ใน V8 ของที่ลบได้มีแต่ของที่ยังไม่เคยถูกเบิก
-- และ SupplyService.delete ลบประวัติของชิ้นนั้นเองก่อนลบตัวของ
CREATE TABLE supply_adjustment (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supply_id   BIGINT      NOT NULL,
    quantity    INTEGER     NOT NULL,
    adjusted_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT supply_adjustment_supply_fk FOREIGN KEY (supply_id) REFERENCES supply_item (id),
    -- แก้แล้วยอดไม่เปลี่ยนไม่ต้องมีแถว
    CONSTRAINT supply_adjustment_quantity_ck CHECK (quantity <> 0)
);

-- อีเมลแจ้งเตือนของใกล้หมด หนึ่งแถวต่อการข้ามเกณฑ์หนึ่งครั้งของของหนึ่งชิ้น
--
-- งานประจำวัน (LowStockAlertService) ทำสามขั้น
--   1. ของที่ถูกเติมจนพ้นเกณฑ์แล้ว ปิดแถวที่ยังเปิดด้วย recovered_at
--   2. ของที่ใกล้หมดแต่ยังไม่มีแถวเปิด เปิดแถวใหม่ (crossed_at)
--   3. แถวเปิดที่ยังไม่ได้ส่ง รวมเป็นอีเมลฉบับเดียวแล้วประทับ sent_at ส่งไม่ออกก็ไม่ประทับ รอบถัดไปจึงส่งใหม่
-- ของที่ยังใกล้หมดอยู่มีแถวเปิดที่ส่งแล้ว จึงไม่ได้อีเมลซ้ำทุกเช้า ของที่ฟื้นแล้วกลับมาใกล้หมดอีกได้แถวใหม่และอีเมลใหม่
--
-- ลบของแล้วแถวหายตาม (CASCADE) เพราะเป็นสถานะของงานแจ้งเตือน ไม่ใช่ประวัติที่ข้อมูลอื่นอ้างถึง
CREATE TABLE low_stock_alert (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supply_id    BIGINT      NOT NULL,
    crossed_at   TIMESTAMPTZ NOT NULL,
    sent_at      TIMESTAMPTZ,
    recovered_at TIMESTAMPTZ,

    CONSTRAINT low_stock_alert_supply_fk FOREIGN KEY (supply_id) REFERENCES supply_item (id) ON DELETE CASCADE
);

-- ของหนึ่งชิ้นมีแถวที่ยังเปิดได้แถวเดียว
-- k8s รัน backend สอง pod งานประจำวันจึงตื่นพร้อมกันสองตัว ขั้นที่ 2 ของทั้งคู่เขียนด้วย ON CONFLICT DO NOTHING บน index นี้
-- ของชิ้นหนึ่งจึงได้แถวเดียวไม่ว่า pod ไหนเขียนก่อน ส่วนขั้นที่ 3 ล็อกแถวแบบ SKIP LOCKED (ดู LowStockAlerts)
CREATE UNIQUE INDEX low_stock_alert_open_uk ON low_stock_alert (supply_id) WHERE recovered_at IS NULL;
