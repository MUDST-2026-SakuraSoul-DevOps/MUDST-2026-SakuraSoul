-- หน่วยน้ำไฟรายเดือนของแต่ละห้อง (SSK-166) นำเข้าจากไฟล์ CSV
-- เป็นยอดใช้ของเดือนนั้น ไม่ใช่เลขมิเตอร์สะสม ไฟเป็น kWh น้ำเป็น m³ ตามที่ใบเสร็จใช้
--
-- ไม่ผูกกับใบเสร็จ ใบเสร็จยังคัดลอกหน่วยที่แอดมินกรอกตอนออกบิลไว้ในตัวเอง (หน้าเว็บเติมหน่วยจากตารางนี้ให้แล้วแก้ได้)
-- การนำเข้าทับค่าเดิมจึงไม่เปลี่ยนบิลที่ออกไปแล้ว
--
-- เป็นประวัติ ไม่ใช่ค่าตั้ง (ทีมตัดสิน 10 พ.ย. 2569) ห้องที่มีค่ามิเตอร์ลบไม่ได้ foreign key จึงไม่ cascade
-- ตัวเช็คที่ให้ข้อความ 409 ที่อ่านรู้เรื่องคือ MeterReadingRoomHistory

CREATE TABLE meter_reading (
    id             BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id        BIGINT         NOT NULL,
    -- วันที่ 1 ของเดือนเสมอ เหมือน receipt.billing_month
    reading_month  DATE           NOT NULL,
    electric_units NUMERIC(10, 2) NOT NULL,
    water_units    NUMERIC(10, 2) NOT NULL,
    -- CSV คือนำเข้าจากไฟล์ MANUAL เผื่อการกรอกทีละห้องในอนาคต ตามสัญญา API ของหน้าเว็บ
    source         VARCHAR(10)    NOT NULL,
    imported_at    TIMESTAMPTZ    NOT NULL,

    CONSTRAINT meter_reading_room_fk FOREIGN KEY (room_id) REFERENCES room (id),
    -- ห้องหนึ่งมีค่าเดือนละชุด นำเข้าซ้ำได้แค่ข้ามหรือทับ (ON CONFLICT ใน MeterReadingService)
    CONSTRAINT meter_reading_room_month_uk UNIQUE (room_id, reading_month),
    CONSTRAINT meter_reading_month_first_day_ck CHECK (EXTRACT(DAY FROM reading_month) = 1),
    CONSTRAINT meter_reading_units_ck CHECK (electric_units >= 0 AND water_units >= 0),
    CONSTRAINT meter_reading_source_ck CHECK (source IN ('CSV', 'MANUAL'))
);

-- GET /api/meter-readings?month= และกราฟการใช้น้ำไฟ (SSK-167) อ่านทีละเดือนหรือช่วงเดือน
CREATE INDEX meter_reading_month_ix ON meter_reading (reading_month);
