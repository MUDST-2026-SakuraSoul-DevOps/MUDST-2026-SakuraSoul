-- อัตราต่อห้องตามช่วงเวลา (SSK-162)
--
-- ห้องหนึ่งมีประวัติอัตราได้หลายแถว แต่ละแถวมีผลตั้งแต่เดือน effective_from ไปจนกว่าจะมีแถวที่ใหม่กว่า
-- อัตรา ณ เดือนหนึ่งคือแถวล่าสุดที่ effective_from <= เดือนนั้น ถ้าไม่มีเลยใช้ค่าตั้งต้นเดิม
-- (ค่าเช่าตาม room_type ของ V12 กับอัตราของ apartment_config ใน V3)
--
-- กติกาจากคอมเมนต์ของอาจารย์ใน SSK-162 และ SSK-180 (31 ต.ค. 2569):
-- - อัตราของห้องมีผลกับ "สัญญาที่ทำตั้งแต่เดือนที่มีผล" เท่านั้น สัญญาเดิมใช้อัตราที่ล็อกไว้ใน lease ตลอดอายุสัญญา
--   ใบเสร็จก็เก็บสำเนาอัตราของตัวเองอยู่แล้ว (V9) จึงไม่มีบิลไหนเปลี่ยนตามแถวในตารางนี้
-- - ตารางนี้เพิ่มอย่างเดียว ไม่มี UPDATE หรือ DELETE ผ่าน API ตั้งผิดให้ตั้งแถวใหม่ทับที่เดือนถัดไป
--
-- ทีมตัดสินวันที่ 10 พ.ย. 2569 ว่าถ้าห้องมีอัตราที่มีผลในเดือนเริ่มสัญญา สัญญาใหม่เอาค่าทั้งห้าตัวจากแถวนั้น
-- ไม่ใช่เฉพาะช่องที่คำขอไม่ได้ส่งมา ดู LeaseService.create

CREATE TABLE room_rate (
    id                     BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id                BIGINT         NOT NULL,
    -- เดือนที่เริ่มมีผล เก็บเป็นวันที่ 1 เหมือน receipt.billing_month จะได้เทียบกันได้ตรง ๆ
    effective_from         DATE           NOT NULL,
    monthly_rent           NUMERIC(10, 2) NOT NULL,
    electric_rate_per_unit NUMERIC(10, 2) NOT NULL,
    water_rate_per_unit    NUMERIC(10, 2) NOT NULL,
    common_area_fee        NUMERIC(10, 2) NOT NULL,
    internet_fee           NUMERIC(10, 2) NOT NULL,
    note                   VARCHAR(200),
    created_at             TIMESTAMPTZ    NOT NULL DEFAULT now(),

    -- อัตราเป็นค่าตั้งของห้อง ไม่ใช่ประวัติที่ต้องเก็บไว้ (สัญญากับใบเสร็จมีสำเนาของตัวเองแล้ว)
    -- ลบห้องหรือย่อผังตึกจึงลบอัตราตามไปด้วย ทีมตัดสินวันที่ 10 พ.ย. 2569 ไม่งั้นตั้งอัตราผิดแถวเดียว
    -- ห้องนั้นจะลบไม่ได้ตลอดไปเพราะตารางนี้ลบแถวไม่ได้
    CONSTRAINT room_rate_room_fk FOREIGN KEY (room_id) REFERENCES room (id) ON DELETE CASCADE,
    -- ห้องหนึ่งเริ่มอัตราใหม่ได้เดือนละครั้ง index ของ constraint นี้ใช้หาอัตราที่มีผลของห้องด้วย
    CONSTRAINT room_rate_room_month_uk UNIQUE (room_id, effective_from),
    CONSTRAINT room_rate_month_first_day_ck CHECK (EXTRACT(DAY FROM effective_from) = 1),
    CONSTRAINT room_rate_amounts_ck CHECK (monthly_rent >= 0
                                       AND electric_rate_per_unit >= 0
                                       AND water_rate_per_unit >= 0
                                       AND common_area_fee >= 0
                                       AND internet_fee >= 0)
);
