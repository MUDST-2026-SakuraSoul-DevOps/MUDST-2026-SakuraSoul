-- ที่เก็บไฟล์กลาง (SSK-161) และคลังเอกสารสแกน (SSK-172)
-- สัญญา API อยู่ที่ docs/api-contract-documents.md กฎที่ทำจริงอยู่ที่ docs/api-contract-phase2-backend.md
--
-- ไฟล์เก็บใน PostgreSQL ไม่ใช่บนดิสก์ของ pod เพราะ backend รันสอง pod และไม่มี volume ร่วม
-- เพิ่มตารางใหม่อย่างเดียว ไม่แตะแถวที่มีอยู่

-- ---------------------------------------------------------------------------------------------------------------
-- ข้อมูลของไฟล์ ไม่มีตัวไฟล์ รายการไฟล์จึงไม่มีทางโหลดไบต์มาด้วย
--
-- เจ้าของเป็นคอลัมน์แยกตามชนิดพร้อม foreign key แบบ ON DELETE CASCADE ไม่ใช่คู่ owner_type/owner_id ลอย ๆ
-- ฐานข้อมูลจึงรู้ว่าเจ้าของคือแถวไหน ลบเจ้าของแล้วไฟล์ตามไปเอง ไม่เหลือแถวกำพร้า (AC ของ SSK-161)
-- โดยไม่ต้องจำไปเพิ่มโค้ดลบในทุกเส้นทางที่ลบเจ้าของ (ตัดสิน 11 พ.ย.: ลบใบแจ้งซ่อมแล้วไฟล์ของใบนั้นหายไปด้วย)
-- ห้ามใช้ RESTRICT เพราะไฟล์แถวเดียวที่ค้างอยู่จะทำให้การลบสัญญาในที่อื่นพัง
--
-- soft delete: deleted_at กับ deleted_by ตั้งคู่กันเสมอ ไฟล์ที่ลบแล้วไม่โผล่ในรายการและดาวน์โหลดไม่ได้
-- แต่ไบต์ยังอยู่ (ตัดสิน 11 พ.ย. เก็บไว้ในเฟสนี้ ยังไม่มีงานล้างข้อมูลตาม PDPA)
-- uploaded_by กับ deleted_by เป็นชื่อผู้ใช้ ไม่ใช่ foreign key ร่องรอยต้องอยู่ได้แม้บัญชีแอดมินถูกลบ
CREATE TABLE attachment (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lease_id     BIGINT,
    ticket_id    BIGINT,
    receipt_id   BIGINT,
    payment_id   BIGINT,
    file_name    VARCHAR(150) NOT NULL,
    content_type VARCHAR(20)  NOT NULL,
    size_bytes   BIGINT       NOT NULL,
    sha256       VARCHAR(64)  NOT NULL,
    uploaded_at  TIMESTAMPTZ  NOT NULL,
    uploaded_by  VARCHAR(50)  NOT NULL,
    deleted_at   TIMESTAMPTZ,
    deleted_by   VARCHAR(50),
    CONSTRAINT attachment_lease_fk   FOREIGN KEY (lease_id)   REFERENCES lease (id)              ON DELETE CASCADE,
    CONSTRAINT attachment_ticket_fk  FOREIGN KEY (ticket_id)  REFERENCES maintenance_ticket (id) ON DELETE CASCADE,
    CONSTRAINT attachment_receipt_fk FOREIGN KEY (receipt_id) REFERENCES receipt (id)            ON DELETE CASCADE,
    CONSTRAINT attachment_payment_fk FOREIGN KEY (payment_id) REFERENCES payment (id)            ON DELETE CASCADE,
    -- เจ้าของหนึ่งรายพอดี
    CONSTRAINT attachment_one_owner_ck    CHECK (num_nonnulls(lease_id, ticket_id, receipt_id, payment_id) = 1),
    CONSTRAINT attachment_content_type_ck CHECK (content_type IN ('application/pdf', 'image/png', 'image/jpeg')),
    -- 1 ไบต์ถึง 5 MB (5 x 1024 x 1024) ตามสัญญา
    CONSTRAINT attachment_size_ck         CHECK (size_bytes BETWEEN 1 AND 5242880),
    CONSTRAINT attachment_sha256_ck       CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT attachment_file_name_ck    CHECK (btrim(file_name) <> ''),
    CONSTRAINT attachment_deleted_ck      CHECK ((deleted_at IS NULL) = (deleted_by IS NULL)
                                                 AND (deleted_at IS NULL OR deleted_at >= uploaded_at))
);

-- รายการไฟล์ของเจ้าของรายหนึ่ง และให้ ON DELETE CASCADE ไม่ต้องไล่ทั้งตาราง
CREATE INDEX attachment_lease_ix   ON attachment (lease_id)   WHERE lease_id   IS NOT NULL;
CREATE INDEX attachment_ticket_ix  ON attachment (ticket_id)  WHERE ticket_id  IS NOT NULL;
CREATE INDEX attachment_receipt_ix ON attachment (receipt_id) WHERE receipt_id IS NOT NULL;
CREATE INDEX attachment_payment_ix ON attachment (payment_id) WHERE payment_id IS NOT NULL;

-- ---------------------------------------------------------------------------------------------------------------
-- ตัวไฟล์ แยกตารางจากข้อมูลของไฟล์ อ่านเฉพาะตอนดาวน์โหลด (DatabaseAttachmentStore)
-- STORAGE EXTERNAL เก็บนอกแถวโดยไม่บีบอัด เพราะ PDF PNG JPEG บีบอัดมาแล้ว บีบซ้ำเปลือง CPU เปล่า ๆ
CREATE TABLE attachment_content (
    attachment_id BIGINT PRIMARY KEY,
    data          BYTEA  NOT NULL,
    CONSTRAINT attachment_content_attachment_fk
        FOREIGN KEY (attachment_id) REFERENCES attachment (id) ON DELETE CASCADE
);
ALTER TABLE attachment_content ALTER COLUMN data SET STORAGE EXTERNAL;

-- ---------------------------------------------------------------------------------------------------------------
-- เอกสารสแกน (SSK-172) คือไฟล์หนึ่งไฟล์ในที่เก็บกลางพร้อมชนิด คำอธิบาย และวันที่สแกน
-- เจ้าของกับ soft delete อยู่ที่แถว attachment ที่เดียว เอกสารกับไฟล์ของมันจึงถูกลบพร้อมกันเสมอ
CREATE TABLE document (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attachment_id BIGINT       NOT NULL,
    document_type VARCHAR(20)  NOT NULL,
    description   VARCHAR(200),
    scan_date     DATE         NOT NULL,
    CONSTRAINT document_attachment_fk FOREIGN KEY (attachment_id) REFERENCES attachment (id) ON DELETE CASCADE,
    CONSTRAINT document_attachment_uk UNIQUE (attachment_id),
    CONSTRAINT document_type_ck CHECK (document_type IN ('CONTRACT_SCAN', 'MAINTENANCE_REPORT', 'RECEIPT_SCAN'))
);

-- รายการเอกสารเรียงวันที่สแกนใหม่สุดก่อน
CREATE INDEX document_scan_date_ix ON document (scan_date DESC, id DESC);
