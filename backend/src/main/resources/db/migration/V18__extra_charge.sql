-- ค่าใช้จ่ายพิเศษต่อห้อง (SSK-165) เช่น ที่จอดรถ ค่าเฟอร์นิเจอร์ เข้าบิลเป็นบรรทัดเพิ่ม
--
-- สามตารางตามชั้นของข้อมูล
-- 1) room_extra_charge  ค่าตั้งของห้อง แอดมินเพิ่ม แก้ ปิด เปิดได้
-- 2) lease_extra_charge สำเนาตอนเซ็นสัญญา (SSK-180) แก้ชื่อหรือยอดของห้องทีหลัง สัญญาเดิมไม่เปลี่ยน
--    รายการที่ห้องได้เพิ่มทีหลังไม่คิดกับสัญญาเดิม เพราะทีมตัดสินว่าไม่ทำ amendment ใน Phase 2
-- 3) receipt_line       สำเนาในใบเสร็จตอนออก บิลเก่าไม่เปลี่ยนเมื่อแก้หรือปิดรายการ (US-16-S3)
--
-- การปิดรายการ (active = false) มีผลกับบิลใหม่ของทุกสัญญาที่มีสำเนา ตามเอกสารของหน้าเว็บ
-- สำเนาในสัญญาจึงไม่มีคอลัมน์ active ของตัวเอง อ่านจากรายการต้นทางตรง ๆ (LeaseExtraCharge.isActive)
-- ไม่ต้องมีโค้ดไล่แก้สำเนาทุกครั้งที่ปิดหรือเปิด และสองที่ไม่มีทางไม่ตรงกัน

CREATE TABLE room_extra_charge (
    id          BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     BIGINT         NOT NULL,
    label       VARCHAR(80)    NOT NULL,
    amount      NUMERIC(10, 2) NOT NULL,
    recurrence  VARCHAR(10)    NOT NULL,
    -- เดือนเก็บเป็นวันที่ 1 เหมือน receipt.billing_month
    start_month DATE           NOT NULL,
    end_month   DATE,
    active      BOOLEAN        NOT NULL DEFAULT TRUE,

    -- เป็นค่าตั้งของห้อง ลบห้องแล้วลบตาม (ทีมตัดสิน 10 พ.ย. 2569 เหมือน room_rate)
    -- ห้องที่เคยมีสัญญาลบไม่ได้อยู่แล้ว รายการที่ถูกคัดลอกเข้าสัญญาหรือบิลจึงไม่โดน cascade
    CONSTRAINT room_extra_charge_room_fk FOREIGN KEY (room_id) REFERENCES room (id) ON DELETE CASCADE,
    CONSTRAINT room_extra_charge_amount_ck CHECK (amount >= 0),
    CONSTRAINT room_extra_charge_recurrence_ck CHECK (recurrence IN ('ONE_TIME', 'MONTHLY')),
    CONSTRAINT room_extra_charge_months_ck CHECK (EXTRACT(DAY FROM start_month) = 1
                                              AND (end_month IS NULL
                                                   OR (EXTRACT(DAY FROM end_month) = 1 AND end_month >= start_month))),
    -- ค่าครั้งเดียวไม่มีเดือนสุดท้าย
    CONSTRAINT room_extra_charge_one_time_no_end_ck CHECK (recurrence = 'MONTHLY' OR end_month IS NULL)
);

CREATE INDEX room_extra_charge_room_ix ON room_extra_charge (room_id);

CREATE TABLE lease_extra_charge (
    id          BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lease_id    BIGINT         NOT NULL,
    charge_id   BIGINT         NOT NULL,
    label       VARCHAR(80)    NOT NULL,
    amount      NUMERIC(10, 2) NOT NULL,
    recurrence  VARCHAR(10)    NOT NULL,
    start_month DATE           NOT NULL,
    end_month   DATE,

    CONSTRAINT lease_extra_charge_lease_fk FOREIGN KEY (lease_id) REFERENCES lease (id),
    -- ไม่ cascade รายการต้นทางที่อยู่ในสัญญาแล้วต้องลบไม่ได้ (ให้ปิดแทน) ExtraChargeService เช็คก่อนเพื่อข้อความที่อ่านรู้เรื่อง
    CONSTRAINT lease_extra_charge_charge_fk FOREIGN KEY (charge_id) REFERENCES room_extra_charge (id),
    CONSTRAINT lease_extra_charge_lease_charge_uk UNIQUE (lease_id, charge_id),
    CONSTRAINT lease_extra_charge_amount_ck CHECK (amount >= 0),
    CONSTRAINT lease_extra_charge_recurrence_ck CHECK (recurrence IN ('ONE_TIME', 'MONTHLY'))
);

CREATE INDEX lease_extra_charge_charge_ix ON lease_extra_charge (charge_id);

CREATE TABLE receipt_line (
    id         BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id BIGINT         NOT NULL,
    -- ซ้ำกับ receipt.lease_id โดยตั้งใจ เพื่อให้ partial unique index ข้างล่างกันค่าครั้งเดียวซ้ำข้ามบิลของสัญญาเดียวกันได้
    lease_id   BIGINT         NOT NULL,
    charge_id  BIGINT         NOT NULL,
    label      VARCHAR(80)    NOT NULL,
    recurrence VARCHAR(10)    NOT NULL,
    amount     NUMERIC(10, 2) NOT NULL,

    CONSTRAINT receipt_line_receipt_fk FOREIGN KEY (receipt_id) REFERENCES receipt (id),
    CONSTRAINT receipt_line_lease_fk FOREIGN KEY (lease_id) REFERENCES lease (id),
    CONSTRAINT receipt_line_charge_fk FOREIGN KEY (charge_id) REFERENCES room_extra_charge (id),
    CONSTRAINT receipt_line_receipt_charge_uk UNIQUE (receipt_id, charge_id),
    CONSTRAINT receipt_line_amount_ck CHECK (amount >= 0),
    CONSTRAINT receipt_line_recurrence_ck CHECK (recurrence IN ('ONE_TIME', 'MONTHLY'))
);

-- ค่าครั้งเดียวคิดได้ครั้งเดียวต่อสัญญา ReceiptService เช็คก่อนออกบิลอยู่แล้ว ตัวนี้กันสองบิลของสัญญาเดียวกัน
-- ที่ออกพร้อมกันพอดีจนเช็คผ่านทั้งคู่
CREATE UNIQUE INDEX receipt_line_one_time_uk ON receipt_line (lease_id, charge_id) WHERE recurrence = 'ONE_TIME';
CREATE INDEX receipt_line_charge_ix ON receipt_line (charge_id);
