-- ปลด NOT NULL ของ line_id (US-03 / SSK-99)
--
-- V6 ตั้ง line_id เป็น NOT NULL ตามคำตัดสินของอาจารย์ (11 ก.ย. 2569) ที่ให้บังคับ
-- Line ID แต่ฟอร์ม Add Tenant ที่ทีมหน้าเว็บ merge เข้ามารอบนี้ยังไม่มีช่องนั้นเลย
-- (ดู SSK-99 และตารางไฟล์ที่ต้องแก้ในหัวข้อ US-03 ของ docs/api-contract-lease.md)
-- ผลคือ body ที่ฟอร์มส่งมาไม่มี lineId ติดมาด้วย ถ้าคอลัมน์ยังบังคับอยู่ ทุกครั้งที่
-- แอดมินกดเพิ่มผู้เช่าจะได้ 400 กลับไป ซึ่งเท่ากับฟีเจอร์เพิ่มผู้เช่าใช้งานไม่ได้เลย
--
-- จึงเปิดให้เป็น NULL ไปก่อนจนกว่าหน้าเว็บจะเพิ่มช่องนี้ให้ครบ พอถึงตอนนั้นค่อยตัดสินใจ
-- ใหม่ว่าจะกลับมาบังคับไหม ข้อมูลที่มีอยู่แล้วไม่ถูกแตะเลย แถวที่ V6 เติม '-' ไว้ก็ยัง
-- เป็น '-' เหมือนเดิม ถ้าอยากตามเก็บให้ค้นแถวที่ line_id = '-'
--
-- ฝั่งโค้ดที่ต้องตรงกับ migration นี้คือ @Column ของ Tenant.lineId ที่เลิกใส่
-- nullable = false และ CreateTenantRequest ที่เลิกใส่ @NotBlank บน lineId
ALTER TABLE tenant ALTER COLUMN line_id DROP NOT NULL;
